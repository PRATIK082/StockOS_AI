def search_stocks(query: str, limit: int = 20) -> list:
    """Search stocks by symbol or name."""
    query = query.upper()
    results = []
    
    for symbol, data in ALL_STOCKS.items():
        if query in symbol.upper() or query in data.get("name", "").upper():
            results.append({
                "symbol": symbol,
                "name": data.get("name", symbol),
                "exchange": data.get("exchange", ""),
                "sector": data.get("sector", ""),
                "currency": data.get("currency", "USD")
            })
            
            if len(results) >= limit:
                break
    
    return results

def get_stock_info(symbol: str) -> dict:
    """Get stock information."""
    # Try exact match first
    if symbol in ALL_STOCKS:
        return ALL_STOCKS[symbol]
    
    # Try with common suffixes
    for suffix in [".NS", ".BO", ""]:
        test_symbol = symbol + suffix
        if test_symbol in ALL_STOCKS:
            return ALL_STOCKS[test_symbol]
    
    # Try with exchange prefix
    for prefix in ["NSE:", "BSE:", "NYSE:", "NASDAQ:"]:
        test_symbol = prefix + symbol
        if test_symbol in ALL_STOCKS:
            return ALL_STOCKS[test_symbol]
    
    # Return basic info if not found
    return {
        "name": symbol,
        "exchange": "UNKNOWN",
        "sector": "Unknown",
        "currency": "USD"
    }